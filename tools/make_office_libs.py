#!/usr/bin/env python3
"""Re-creates netlify/lib/office-kor.mjs and office-inv.mjs from the POS app's korona.js and invoice.js
(the same code the Mac app runs), with logins taken from Netlify settings instead of files on a Mac.
Run:  python3 tools/make_office_libs.py [path/to/pos-app]"""
import re, sys, os
pos = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', '..', 'pos-app')
out = os.path.join(os.path.dirname(__file__), '..', 'netlify', 'lib')

def sub(s, pat, rep, count=1, flags=re.S):
    n = re.subn(pat, lambda m: rep, s, count=count, flags=flags)
    assert n[1] == count, ('no match', pat)
    return n[0]

k = open(os.path.join(pos, 'korona.js')).read()
k = k.replace("const fs = require('fs');\nconst path = require('path');\n", "")
k = sub(k, r"  const file = path\.join\(o\.userData, 'korona-settings\.json'\);\n", "")
k = sub(k, r"  const read = \(\) => \{.*?\n  const efile = path\.join\(o\.userData, 'korona-edit\.json'\);\n  const readEdit = \(\) => \{.*?\n  const write = \(s\) => \{.*?\n",
 "  const env = (n) => (typeof process !== 'undefined' && process.env && process.env[n]) || '';\n"
 "  const read = () => ({ host: env('KORONA_HOST') || DEFAULT_HOST, account: env('KORONA_ACCOUNT_ID'), user: env('KORONA_USER'), password: env('KORONA_PASSWORD') });\n"
 "  const readEdit = () => ({ user: env('KORONA_EDIT_USER'), password: env('KORONA_EDIT_PASSWORD') });\n"
 "  const write = () => {};\n")
k = sub(k, r"    save\(v\) \{.*?\n", "    save() { return k.info(); },\n")
k = sub(k, r"    clear\(\) \{.*?\n", "    clear() { return k.info(); },\n")
k = sub(k, r"    editSave\(v\) \{.*?\n", "    editSave() { return k.editInfo(); },\n")
k = sub(k, r"    editClear\(\) \{.*?\n", "    editClear() { return k.editInfo(); },\n")
k = k.replace("module.exports = { makeKorona };", "")
k = k.replace("function makeKorona(o) {", "export function makeKorona(o) {")
k = "// GENERATED by tools/make_office_libs.py from the POS app's korona.js. Do not edit by hand.\n// Logins come from Netlify settings: KORONA_HOST, KORONA_ACCOUNT_ID, KORONA_USER, KORONA_PASSWORD (read only) and KORONA_EDIT_USER, KORONA_EDIT_PASSWORD (receipts and products, never booking).\n" + k
open(os.path.join(out, 'office-kor.mjs'), 'w').write(k)

i = open(os.path.join(pos, 'invoice.js')).read()
i = i.replace("const fs = require('fs');\nconst path = require('path');\n", "")
i = sub(i, r"  const keyFile = path\.join\(o\.userData, 'anthropic-key\.txt'\);\n", "")
i = sub(i, r"  const key = \(\) => \{.*?\n", "  const key = () => ((typeof process !== 'undefined' && process.env && process.env.ANTHROPIC_API_KEY) || '').trim();\n")
i = sub(i, r"    setKey\(k\) \{.*?\n", "    setKey() { return this.info(); },\n")
i = i.replace("module.exports = { makeInvoice };", "")
i = i.replace("function makeInvoice(o) {", "export function makeInvoice(o) {")
i = i.replace("Check the key in Settings.", "Check ANTHROPIC_API_KEY in Netlify.").replace("Paste the Anthropic API key in Settings first.", "The Anthropic key is not set up in Netlify yet (ANTHROPIC_API_KEY).")
i = "// GENERATED by tools/make_office_libs.py from the POS app's invoice.js. Do not edit by hand.\n// The key comes from the Netlify setting ANTHROPIC_API_KEY.\n" + i
open(os.path.join(out, 'office-inv.mjs'), 'w').write(i)
print('ok')
